// 按规则推导某难「应有之道」（必给）与「可有之道」（允许给，不强制）
//   res → 渡（必）；boss/pet → 逆（可）；mon → 战（可）；tre → 夺（可）
NDX.trialDaoNeed = function trialDaoNeed(id) {
  const r = NDX.TRIAL_DAO_RULE[id] || {};
  const must = [];
  const may = [];
  if (r.res) must.push('渡');
  if (r.boss || r.pet) may.push('逆');
  if (r.mon) may.push('战');
  if (r.tre) may.push('夺');
  return { must: must, may: may, rule: r };
};

