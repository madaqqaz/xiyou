// 旧存档 materials 键 1:1 折算进新名（restoreRun 时调用；幂等可重入）
NDX.migrateLegacyMaterials = function (s) {
  if (!s || !s.materials) return false;
  let hit = false;
  Object.keys(NDX.MAT_LEGACY_MAP).forEach((old) => {
    const n = s.materials[old];
    if (typeof n === 'number' && n > 0) {
      const nw = NDX.MAT_LEGACY_MAP[old];
      s.materials[nw] = (s.materials[nw] || 0) + n;
      delete s.materials[old];
      hit = true;
    }
  });
  return hit;
};
